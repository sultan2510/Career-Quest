"""Data schemas and models using Pydantic."""

from typing import List, Dict, Any, Optional, Union
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict
from enum import Enum


class DecisionType(str, Enum):
    """Types of decisions in career scenarios."""
    INDIVIDUAL = "individual"
    TEAM = "team"
    LEADERSHIP = "leadership"
    STEALTH = "stealth"


class ScenarioTheme(str, Enum):
    """Themes for career scenarios."""
    ETHICS = "ethics"
    COMPETITION = "competition"
    INNOVATION = "innovation"
    CAREER_DEVELOPMENT = "career_development"
    PERSONAL_GROWTH = "personal_growth"


class UserStatus(str, Enum):
    """User status indicators."""
    NEW = "new"
    ACTIVE = "active"
    LAPSED = "lapsed"


class SkillLevel(str, Enum):
    """Skill proficiency levels."""
    NOVICE = "novice"
    APPRENTICE = "apprentice"
    PRACTITIONER = "practitioner"
    EXPERT = "expert"
    MASTER = "master"


class CareerField(str, Enum):
    """Career field categories."""
    TECHNOLOGY = "technology"
    HEALTHCARE = "healthcare"
    FINANCE = "finance"
    EDUCATION = "education"
    ENVIRONMENT = "environment"
    ARTS = "arts"
    GOVERNMENT = "government"
    NONPROFIT = "nonprofit"
    ACADEMIC = "academic"
    ENTREPRENEURSHIP = "entrepreneurship"


# Base models
class BaseUser(BaseModel):
    """Base user information."""
    user_id: str
    name: Optional[str] = None
    email: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class BaseCareer(BaseModel):
    """Base career information."""
    career_id: str
    title: str
    field: CareerField
    description: str

    model_config = ConfigDict(from_attributes=True)


class BaseScenario(BaseModel):
    """Base scenario information."""
    scenario_id: str
    title: str
    description: str
    theme: ScenarioTheme
    difficulty: int = Field(ge=1, le=10)

    model_config = ConfigDict(from_attributes=True)


# User models
class UserProfile(BaseUser):
    """Extended user profile with career interests."""
    skills: Dict[str, SkillLevel] = Field(default_factory=dict)
    interests: List[str] = Field(default_factory=list)
    values: List[str] = Field(default_factory=list)
    experience_years: int = 0
    education_level: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class UserHistory(BaseModel):
    """User interaction history."""
    user_id: str
    completed_scenarios: List[str] = Field(default_factory=list)
    decision_history: List[Dict[str, Any]] = Field(default_factory=list)
    current_progress: Optional[Dict[str, Any]] = None
    last_active: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# Career models
class CareerSkill(BaseModel):
    """Required skill for a career."""
    name: str
    recommended_level: SkillLevel
    weight: float = Field(ge=0, le=1)


class CareerPath(BaseModel):
    """Detailed career path information."""
    career_id: str
    title: str
    description: str
    required_skills: List[CareerSkill]
    typical_salary_range: tuple[Optional[int], Optional[int]]
    growth_rate: float
    work_environment: str
    education_requirements: str


# Scenario models
class DecisionOption(BaseModel):
    """A decision option within a scenario."""
    option_id: str
    text: str
    description: str
    consequences: List[str] = Field(default_factory=list)


class ScenarioChoice(BaseModel):
    """A choice point in a scenario."""
    choice_id: str
    question: str
    options: List[DecisionOption]
    best_practice_paths: List[str] = Field(default_factory=list)


class FullScenario(BaseScenario):
    """Complete scenario with all details."""
    career_alignment: Optional[str] = None
    decision_points: List[ScenarioChoice] = Field(default_factory=list)
    context: str = ""
    learning_objectives: List[str] = Field(default_factory=list)


# RAG-specific models
class ProfileVector(BaseModel):
    """User profile vector for retrieval."""
    user_id: str
    embedding: List[float] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(from_attributes=True)


class RetrievalResult(BaseModel):
    """Result from retrieval operation."""
    item_id: str
    item_type: str
    content: str
    score: float
    metadata: Dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(from_attributes=True)


class GeneratedResponse(BaseModel):
    """Response generated by the RAG system."""
    content: str
    confidence: float = Field(ge=0, le=1)
    sources: List[str] = Field(default_factory=list)
    citations: List[Dict[str, Any]] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)


# Satisfaction models
class SatisfactionOutcome(BaseModel):
    """Historical satisfaction outcome."""
    outcome_id: str
    user_id: str
    scenario_id: str
    career_path: str
    satisfaction_score: float = Field(ge=0, le=10)
    feedback_text: Optional[str] = None
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class OutcomePredictorInput(BaseModel):
    """Input for satisfaction prediction."""
    user_id: str
    scenario_id: str
    decision_made: str
    historical_similarity: float = 0.0
    contextual_factors: Dict[str, Any] = Field(default_factory=dict)


# Decision models
class DecisionPoint(BaseModel):
    """A decision point for scoring."""
    user_id: str
    scenario_id: str
    choice_id: str
    context: Optional[str] = None


# Database models
class DatabaseInfo(BaseModel):
    """Database connection information."""
    url: str
    pool_size: int = 10
    max_overflow: int = 20
    pool_timeout: int = 30


