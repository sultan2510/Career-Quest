class DimensionScore(BaseModel):
    """Score for a single intelligence dimension."""
    raw_score: float = 0.0
    max_possible: float = 0.0
    percentile: Optional[float] = None
    confidence: str = "very_low"  # Use string for enum compatibility
    scenarios_assessed: int = 0
    max_tier_reached: int = 0
    score_history: List[float] = Field(default_factory=list)
    last_updated: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class LearningTrajectory(BaseModel):
    """Tracks learning ability through performance improvement over time."""
    trial_scores: List[float] = Field(default_factory=list)
    trial_timestamps: List[datetime] = Field(default_factory=list)
    trajectory_type: Optional[str] = None
    growth_rate: float = 0.0
    consistency: float = 0.0


class IntelligenceProfile(BaseModel):
    """Complete multi-dimensional intelligence profile for a user."""
    user_id: str
    session_id: str
    dimensions: Dict[str, DimensionScore] = Field(default_factory=dict)
    learning_trajectory: LearningTrajectory = Field(default_factory=LearningTrajectory)
    riasec_scores: Dict[str, float] = Field(default_factory=dict)
    riasec_code: Optional[str] = None
    total_scenarios_completed: int = 0
    total_branches_explored: int = 0
    flagged_inconsistencies: List[Dict[str, Any]] = Field(default_factory=list)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ProfileVectorModel(BaseModel):
    """Mathematical vector representation of the intelligence profile."""
    user_id: str
    vector: List[float] = Field(default_factory=list)
    dimension_order: List[str] = Field(default_factory=list)
    confidence_vector: List[float] = Field(default_factory=list)
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    def to_dict(self) -> Dict[str, float]:
        """Convert to dictionary mapping dimension names to scores."""
        dimension_names = [
            "spatial_transformational",
            "spatial_analytical",
            "spatial_object_visual",
            "logical_mathematical",
            "verbal_linguistic",
            "interpersonal",
            "intrapersonal",
            "bodily_kinesthetic",
            "musical",
            "naturalistic",
            "existential",
            "fluid_intelligence",
            "learning_ability",
            "career_adaptability",
            "creative_problem_solving",
            "emotional_intelligence",
            "leadership",
            "systems_thinking",
        ]
        return dict(zip(dimension_names, self.vector))


