"""XGBoost-powered DNA dimension scoring, trained on synthetic data derived
from the deterministic rubric so predictions are consistent with the existing
scoring logic while demonstrating real ML inference for the hackathon.

The model predicts each intelligence dimension's score from a vector of
scenario response indicators. Training data is generated from catalog scoring
vectors (see train_xgboost.py). At inference time, the trained booster reads
scenario selections and outputs per-dimension scores, which are combined with
the deterministic scorer for a hybrid result.
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

from config.settings import IntelligenceDimension
from scoring.deterministic_scorer import (
    DeterministicScorer,
    IntelligenceProfile,
    Scenario,
    ScenarioResponse,
)

logger = logging.getLogger(__name__)
MODEL_DIR = Path(__file__).resolve().parent
MODEL_PATH = MODEL_DIR / "dna_xgboost.json"

DIMENSIONS = list(IntelligenceDimension)


class XGBoostScorer:
    """ML-augmented scorer that blends XGBoost predictions with deterministic rubrics.

    Loads a pre-trained XGBoost model (dna_xgboost.json) generated by
    train_xgboost.py. If the model artifact is missing or xgboost is not
    installed, falls back to pure deterministic scoring with zero overhead.
    """

    def __init__(self, model_path: Path | None = None):
        self._model_path = model_path or MODEL_PATH
        self._booster: Any = None
        self._feature_names: List[str] = []
        self._dimension_index: Dict[str, int] = {}
        self.available = self._try_load()

    def _try_load(self) -> bool:
        if not self._model_path.exists():
            return False
        try:
            import base64
            import tempfile
            import xgboost as xgb  # type: ignore
            with open(self._model_path, encoding="utf-8") as f:
                data = json.load(f)
            self._feature_names = data.get("feature_names", [])
            self._dimension_index = data.get("dimension_index", {})
            # Load each per-dimension booster from base64-encoded JSON
            self._boosters: list[xgb.Booster] = []
            for model_entry in data.get("models", []):
                booster_bytes = base64.b64decode(model_entry["booster_b64"])
                with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp:
                    tmp_path = tmp.name
                Path(tmp_path).write_bytes(booster_bytes)
                booster = xgb.Booster()
                booster.load_model(tmp_path)
                Path(tmp_path).unlink(missing_ok=True)
                self._boosters.append(booster)
            return len(self._boosters) == len(DIMENSIONS)
        except Exception as e:
            logger.warning("XGBoost model failed to load (%s); using deterministic scorer only", e)
            self._boosters = []
            self._feature_names = []
            self._dimension_index = {}
            return False

    def encode_responses(self, profile: IntelligenceProfile, scenarios: List[Scenario],
                         selected_answers: dict[str, str] | None = None) -> np.ndarray:
        """Build a feature vector from scenario response history for each dimension.

        ``selected_answers`` maps scenario_id -> selected_option_id for answered
        scenarios. If omitted, the method attempts to use a stale profile history
        (which is typically empty in the current architecture).
        """
        if selected_answers is None:
            selected_answers = {resp.scenario_id: resp.selected_option_id
                                for resp in _extract_responses(profile)}
        # Feature: one-hot encoded responses across all scenario options
        # plus dimension-specific aggregates from the deterministic scorer
        features: List[float] = []
        for scenario in scenarios:
            for option in scenario.response_options:
                selected = selected_answers.get(scenario.scenario_id) == option.option_id
                features.append(1.0 if selected else 0.0)
        for dim in DIMENSIONS:
            score = profile.dimensions.get(dim)
            features.append(score.raw_score if score else 0.0)
        return np.array(features, dtype=np.float32)

    def predict(self, profile: IntelligenceProfile, scenarios: List[Scenario],
                selected_answers: dict[str, str] | None = None) -> Dict[IntelligenceDimension, float]:
        """Predict raw dimension scores using XGBoost. Returns empty dict if unavailable."""
        if not self.available or not getattr(self, "_boosters", None):
            return {}
        features = self.encode_responses(profile, scenarios, selected_answers).reshape(1, -1)
        try:
            import xgboost as xgb
            dmatrix = xgb.DMatrix(features, feature_names=self._feature_names)
            result: Dict[IntelligenceDimension, float] = {}
            for i, booster in enumerate(self._boosters):
                pred = booster.predict(dmatrix)
                dim = DIMENSIONS[i]
                result[dim] = float(pred[0])
            return result
        except Exception as e:
            logger.warning("XGBoost inference failed: %s", e)
            return {}

    def score_response(self, profile: IntelligenceProfile,
                       scenario: Scenario, response: ScenarioResponse,
                       catalog_scenarios: List[Scenario]) -> IntelligenceProfile:
        """Overlay ML predictions on a deterministically-scored profile.

        ``catalog_scenarios`` must contain ALL catalog scenarios (in the same
        order used at training time) so the feature vector matches the model's
        expected feature space. Only the single answered response drives the
        one-hot signal.
        """
        selected_answers = {response.scenario_id: response.selected_option_id}
        ml_scores = self.predict(profile, catalog_scenarios, selected_answers)
        for dim, ml_score in ml_scores.items():
            dim_score = profile.dimensions.get(dim)
            if dim_score:
                blend = 0.7 * dim_score.raw_score + 0.3 * ml_score
                dim_score.raw_score = blend
        return profile


def _extract_responses(profile: IntelligenceProfile) -> List[ScenarioResponse]:
    """Extract scenario responses from profile history (legacy stub).

    The deterministic scorer does not retain response history on the profile,
    so this returns an empty list. Callers should pass ``selected_answers``
    explicitly to ``encode_responses`` / ``predict`` instead.
    """
    return []


def load_scorer() -> XGBoostScorer:
    """Module-level singleton for reuse within a serverless invocation."""
    return XGBoostScorer()
